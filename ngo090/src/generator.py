"""Generator of PaySim-format transactions for the live simulation.

Normal traffic follows PaySim's mix of types and typical amounts. Fraud is
generated by one of two patterns:

    PaySim pattern        the account is emptied into another account (TRANSFER or CASH_OUT).
                          This is the pattern the engine was trained on, so the engine
                          should do well on it. The report must say that the generator
                          matches the training data.
    Small transfers       modest transfers between accounts that already hold money. The
                          engine learned "the sender's balance is emptied into an empty
                          receiver", so this pattern slips through: switching it on shows
                          how the system behaves when fraud changes shape.

The true label (isFraud) is kept in the generated table for judging results
afterwards. The risk engine never receives it.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

PATTERN_PAYSIM = "PaySim pattern"
PATTERN_SMALL = "Small transfers between established accounts"

_TYPES = ("PAYMENT", "CASH_IN", "CASH_OUT", "TRANSFER", "DEBIT")
# Mix and amounts follow the replayed PaySim window (results/<run>/replay_sample.csv.gz),
# so live traffic looks like the traffic the engine was validated on. A generator that
# produces much riskier transactions than PaySim would flood the review queue and make
# the drift monitor fire on healthy traffic.
_TYPE_PROBS = (0.34, 0.22, 0.35, 0.08, 0.01)
_MEDIAN_AMOUNT = {"PAYMENT": 9_000, "CASH_IN": 90_000, "CASH_OUT": 145_000, "TRANSFER": 410_000, "DEBIT": 3_000}
_MEDIAN_DEST = 450_000          # receiver balance before, when the account is not empty
DEST_ZERO_SHARE = 0.16          # share of honest transactions paid into an empty account
FRAUD_DEST_ZERO = 0.66          # ... and of fraudulent ones

# Busier in the day than at night (simulated clock), shaped like the replay window.
_HOUR_WEIGHT = np.array([0.01, 0.01, 0.01, 0.01, 0.01, 0.01, 0.01, 0.02, 0.03, 0.05, 0.06, 0.05,
                         0.07, 0.09, 0.09, 0.06, 0.09, 0.05, 0.14, 0.09, 0.10, 0.06, 0.05, 0.03])

COLUMNS = ["id", "minute", "step", "hour", "type", "amount", "oldbalanceOrg", "oldbalanceDest", "isFraud", "pattern"]


@dataclass(frozen=True)
class GeneratorConfig:
    volume_per_hour: int = 300      # average transactions per simulated hour
    fraud_rate: float = 0.03        # share of transactions that are fraud
    new_pattern: bool = False       # also generate fraud the engine was not trained on
    market_shift: bool = False      # the market changes: amounts 10x larger, receivers are new accounts

    def __post_init__(self) -> None:
        if self.volume_per_hour < 1:
            raise ValueError("volume_per_hour must be at least 1.")
        if not 0.0 <= self.fraud_rate <= 1.0:
            raise ValueError("fraud_rate must be between 0 and 1.")


class TransactionGenerator:
    """Draws transactions minute by minute of simulated time."""

    def __init__(self, seed: int | None = None):
        self.rng = np.random.default_rng(seed)
        self._next_id = 1

    def generate(self, minute_start: int, minute_end: int, config: GeneratorConfig) -> pd.DataFrame:
        """All transactions of the simulated minutes [minute_start, minute_end)."""
        rng = self.rng
        minutes = np.arange(minute_start, minute_end)
        if len(minutes) == 0:
            return pd.DataFrame(columns=COLUMNS)
        rate = config.volume_per_hour / 60.0 * _HOUR_WEIGHT[(minutes // 60) % 24] / _HOUR_WEIGHT.mean()
        counts = rng.poisson(rate)
        minute = np.repeat(minutes, counts)
        n = len(minute)
        if n == 0:
            return pd.DataFrame(columns=COLUMNS)

        # normal traffic
        typ = rng.choice(_TYPES, n, p=_TYPE_PROBS).astype(object)
        median = np.array([_MEDIAN_AMOUNT[t] for t in typ], dtype=float)
        amount = rng.lognormal(np.log(median), 0.9)
        sender = amount * rng.uniform(1.1, 15.0, n)                 # honest senders keep money left over
        dest = np.where(typ == "PAYMENT", 0.0,
                        np.where(rng.random(n) < DEST_ZERO_SHARE, 0.0,
                                 rng.lognormal(np.log(_MEDIAN_DEST), 1.6, n)))

        # fraud overwrites some of the rows
        fraud = rng.random(n) < config.fraud_rate
        pattern = np.full(n, "", dtype=object)
        small = fraud & config.new_pattern & (rng.random(n) < 0.5)
        drain = fraud & ~small

        typ[drain] = rng.choice(["TRANSFER", "CASH_OUT"], drain.sum())
        amount[drain] = np.clip(rng.lognormal(np.log(450_000), 1.0, drain.sum()), 5_000, 10_000_000)
        sender[drain] = np.where(rng.random(drain.sum()) < 0.9, amount[drain],
                                 amount[drain] * rng.uniform(1.0, 1.2, drain.sum()))
        dest[drain] = np.where((typ[drain] == "TRANSFER") | (rng.random(drain.sum()) < FRAUD_DEST_ZERO),
                               0.0, rng.lognormal(np.log(_MEDIAN_DEST), 1.6, drain.sum()))
        pattern[drain] = PATTERN_PAYSIM

        typ[small] = "TRANSFER"
        amount[small] = np.clip(rng.lognormal(np.log(8_000), 0.4, small.sum()), 1_500, 20_000)
        sender[small] = amount[small] * rng.uniform(1.5, 4.0, small.sum())
        # Money moves between accounts that already hold funds: no emptied sender,
        # no new receiver. That is exactly what the trained rule does not look for.
        dest[small] = rng.lognormal(np.log(_MEDIAN_DEST), 1.6, small.sum())
        pattern[small] = PATTERN_SMALL

        if config.market_shift:
            amount, sender = amount * 10.0, sender * 10.0
            dest = np.where(typ == "PAYMENT", dest, 0.0)

        ids = np.arange(self._next_id, self._next_id + n)
        self._next_id += n
        return pd.DataFrame({
            "id": ids, "minute": minute, "step": minute // 60 + 1, "hour": (minute // 60) % 24,
            "type": typ, "amount": amount.round(2), "oldbalanceOrg": sender.round(2),
            "oldbalanceDest": dest.round(2), "isFraud": fraud.astype(int), "pattern": pattern,
        })